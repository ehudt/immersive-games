export const LANDMARK_COUNT = 33;

export interface Vec3 {
  x: number;
  y: number;
  z: number;
}

export interface Landmark extends Vec3 {
  /** 0..1 likelihood the point is visible (not occluded / in frame). */
  visibility: number;
}

/**
 * One frame of raw pose data, as produced by a pose tracker.
 *
 * `image` landmarks are normalized to the camera image (x right, y down, 0..1),
 * NOT mirrored. `world` landmarks are metric, hip-centered, x right / y down /
 * z away from camera — MediaPipe conventions.
 */
export interface PoseFrame {
  /** performance.now() timestamp in ms. */
  time: number;
  image: Landmark[];
  world: Landmark[];
}

